/// Result of a full two-layer parallel decode.
#[derive(Debug, Clone)]
pub struct ParallelDecodeResult {
    /// Global edge indices that were committed (union of layer-0 commits and
    /// layer-1 commits).  Sorted and deduplicated.
    pub committed_edges: Vec<usize>,
    /// Global logical observable parity (XOR of `edge_observables` along
    /// committed edges).  One entry per logical observable; `true` means the
    /// observable was flipped an odd number of times.
    pub logical_parity: Vec<bool>,
    /// Number of defects that were handled by offloaded (pre-matched) logic
    /// inside the inner decoders — reported for benchmarking.
    pub total_offloaded: usize,
}

/// Build a *window* `SolverInitializer` from the global graph.
///
/// * For `Open` windows, for every global edge that connects a real detector
///   inside the window to a real detector outside, we add a local edge from
///   the inside endpoint to a new *temporal virtual* vertex.  The weight and
///   observable label are copied from the global edge.  This makes a defect
///   at the time boundary matchable to the temporal boundary at the same cost
///   as the original error that would have crossed the cut.
/// * For `Closed` windows, crossing edges are omitted entirely.
///
/// Spatial virtual vertices are always included (they are global code
/// boundaries, not window artefacts).
pub fn build_window_initializer(
    global: &MicroBlossomSingle,
    window: &WindowSpec,
) -> (SolverInitializer, Vec<VisualizePosition>, WindowMaps) {
    let global_init = global.get_initializer();
    let global_pos = global.get_positions();

    // Map global vertex index -> local vertex index (None = outside window)
    let mut global_to_local: Vec<Option<usize>> = vec![None; global.vertex_num];
    let mut local_to_global: Vec<usize> = Vec::new();
    let mut local_positions: Vec<VisualizePosition> = Vec::new();

    // 1. Collect real detectors inside time interval.
    for (v_idx, pos) in global_pos.iter().enumerate() {
        if window.contains(pos.t) {
            let local = local_positions.len();
            global_to_local[v_idx] = Some(local);
            local_to_global.push(v_idx);
            local_positions.push(pos.clone());
        }
    }

    // 2. Always include spatial virtual vertices (they have no meaningful t but
    // are needed for code boundaries).  We include them even if their synthetic
    // position's t is outside the interval, because they are not time-like.
    let spatial_virtuals: BTreeSet<usize> = global_init.virtual_vertices.iter().copied().collect();
    for &v in &global_init.virtual_vertices {
        if global_to_local[v].is_none() {
            // Virtual vertices may have been included already if their t happened
            // to be inside; otherwise add them.
            let local = local_positions.len();
            global_to_local[v] = Some(local);
            local_to_global.push(v);
            // Use global position for virtual if available, otherwise synthetic at window centre.
            let pos = global_pos
                .get(v)
                .cloned()
                .unwrap_or_else(|| VisualizePosition::new(0.0, 0.0, (window.t_start + window.t_end) / 2.0));
            local_positions.push(pos);
        }
    }

    // 3. For open windows, add temporal virtual vertices.
    let mut temporal_virtuals: Vec<usize> = Vec::new(); // local indices
    if window.is_open() {
        // Past boundary
        let past_local = local_positions.len();
        local_positions.push(VisualizePosition::new(0.0, 0.0, window.t_start));
        local_to_global.push(usize::MAX); // sentinel: no global counterpart
        temporal_virtuals.push(past_local);
        // Future boundary
        let future_local = local_positions.len();
        local_positions.push(VisualizePosition::new(0.0, 0.0, window.t_end));
        local_to_global.push(usize::MAX);
        temporal_virtuals.push(future_local);
    }

    let local_vertex_num = local_positions.len();

    // 4. Build local edges.
    let mut local_edges: Vec<(usize, usize, Weight)> = Vec::new();
    let mut local_to_global_edge: Vec<usize> = Vec::new();
    // Map from (local_u, local_v) to check duplicates (rare)
    for (global_edge_idx, edge) in global.weighted_edges.iter().enumerate() {
        let l = edge.l;
        let r = edge.r;
        let w = edge.w;
        let l_inside = global_to_local.get(l).and_then(|o| *o);
        let r_inside = global_to_local.get(r).and_then(|o| *o);
        match (l_inside, r_inside) {
            (Some(ll), Some(rr)) => {
                // Both endpoints inside — keep edge as is.
                local_edges.push((ll, rr, w));
                local_to_global_edge.push(global_edge_idx);
            }
            (Some(ll), None) => {
                // l inside, r outside — crossing edge.
                if window.is_open() {
                    // Route to appropriate temporal virtual: past if outside t < t_start, future otherwise.
                    let outside_t = global_pos.get(r).map(|p| p.t).unwrap_or(window.t_end);
                    let virt = if outside_t < window.t_start {
                        temporal_virtuals[0]
                    } else {
                        temporal_virtuals[1]
                    };
                    local_edges.push((ll, virt, w));
                    local_to_global_edge.push(global_edge_idx);
                } else {
                    // Closed: omit
                }
            }
            (None, Some(rr)) => {
                if window.is_open() {
                    let outside_t = global_pos.get(l).map(|p| p.t).unwrap_or(window.t_start);
                    let virt = if outside_t < window.t_start {
                        temporal_virtuals[0]
                    } else {
                        temporal_virtuals[1]
                    };
                    local_edges.push((rr, virt, w));
                    local_to_global_edge.push(global_edge_idx);
                }
            }
            (None, None) => {
                // Both outside — irrelevant for this window.
            }
        }
    }

    // 5. Virtual vertices for local graph: spatial + temporal
    let mut local_virtuals: Vec<usize> = Vec::new();
    for &gv in &global_init.virtual_vertices {
        if let Some(lv) = global_to_local[gv] {
            local_virtuals.push(lv);
        }
    }
    local_virtuals.extend(temporal_virtuals.iter().copied());

    let local_initializer = SolverInitializer::new(local_vertex_num, local_edges, local_virtuals);

    let maps = WindowMaps {
        local_to_global_vertex: local_to_global,
        local_to_global_edge,
        global_to_local,
    };

    (local_initializer, local_positions, maps)
}

/// Bidirectional maps between global and window-local indices.
#[derive(Debug, Clone)]
pub struct WindowMaps {
    /// `local_vertex -> global_vertex` (`usize::MAX` for temporal virtuals).
    pub local_to_global_vertex: Vec<usize>,
    /// `local_edge -> global_edge`
    pub local_to_global_edge: Vec<usize>,
    /// `global_vertex -> Option<local_vertex>`
    pub global_to_local: Vec<Option<usize>>,
}

impl WindowMaps {
    pub fn global_defects_to_local(&self, global_defects: &[VertexIndex]) -> Vec<VertexIndex> {
        let mut out = Vec::new();
        for &gv in global_defects {
            if let Some(Some(lv)) = self.global_to_local.get(gv).copied() {
                out.push(lv);
            }
        }
        out
    }
}

/// An already-cut window graph with explicit detector/edge maps from the
/// toolchain. Unlike `WindowSpec`, membership is by detector ID, not an inferred
/// time interval; the two representations must not be silently conflated.
pub struct EncodedWindow {
    pub id: String,
    pub layer: WindowLayer,
    pub initializer: SolverInitializer,
    pub positions: Vec<VisualizePosition>,
    /// `local vertex -> global detector`, or None for either virtual boundary.
    pub detector_map: Vec<Option<usize>>,
    /// `local edge -> global edge`, aligned with `initializer.weighted_edges`.
    pub edge_map: Vec<usize>,
    /// Global edges owned by the top commit; bottom windows commit every edge.
    pub commit_edges: Vec<usize>,
    /// Explicit detector commit membership, used to check layer-0 parity.
    pub commit_detectors: Vec<usize>,
}

/// Parallel-window decoder that wraps any micro-blossom inner solver.
///
/// The generic `Inner` is a *window* solver factory: given a
/// `MicroBlossomSingle` graph it produces a solver that implements
/// `PrimalDualSolver` (fusion-blossom trait).  For the prototype we use
/// `SolverEmbeddedComb` (the heterogeneous CPU+comb-accelerator split) but
/// any `PrimalDualSolver` can be plugged in, matching the paper's claim that
/// parallel windows are compatible with "any inner decoder that returns an
/// (approximately) minimum weight solution" (MWPM or Union-Find).
pub struct ParallelWindowDecoder {
    pub global_graph: MicroBlossomSingle,
    pub windows: Vec<WindowSpec>,
    /// Edge observables in global order: `edge_observables[e]` is `Some(k)` if
    /// the error mechanism for that edge flips logical observable `k`, or `None`
    /// if it has no logical effect.  For multi-observable codes this can be
    /// extended to `Vec<usize>`.
    pub edge_observables: Vec<Option<usize>>,
    pub num_observables: usize,
    // The explicit-membership path uses the actual graphs exported by the
    // toolchain and preserves *all* logical labels per edge.
    encoded_windows: Option<Vec<EncodedWindow>>,
    encoded_observables: Vec<Vec<usize>>,
}

impl ParallelWindowDecoder {
    pub fn new(
        global_graph: MicroBlossomSingle,
        windows: Vec<WindowSpec>,
        edge_observables: Vec<Option<usize>>,
        num_observables: usize,
    ) -> Self {
        assert_eq!(
            global_graph.weighted_edges.len(),
            edge_observables.len(),
            "edge_observables must be index-aligned with global weighted_edges"
        );
        // Validate windows once at construction
        for w in &windows {
            w.validate().expect("invalid window spec");
        }
        let virtuals: BTreeSet<_> = global_graph.virtual_vertices.iter().copied().collect();
        let mut claimed = BTreeSet::new();
        for w in windows.iter().filter(|w| w.layer == WindowLayer::Top) {
            for (eid, e) in global_graph.weighted_edges.iter().enumerate() {
                let endpoints = [e.l, e.r];
                let real: Vec<_> = endpoints.iter().copied().filter(|v| !virtuals.contains(v)).collect();
                if real.iter().any(|&v| w.is_commit(global_graph.positions[v].t)) {
                    assert!(
                        real.iter().all(|&v| w.contains(global_graph.positions[v].t)),
                        "window {} incident edge {eid} crosses outer boundary; enlarge buffer",
                        w.id
                    );
                    assert!(claimed.insert(eid), "global edge {eid} claimed by multiple top windows");
                }
            }
        }
        Self {
            global_graph,
            windows,
            edge_observables,
            num_observables,
            encoded_windows: None,
            encoded_observables: Vec::new(),
        }
    }

    /// Construct a decoder from window graphs already cut by the toolchain.
    /// The caller must provide unambiguous top-commit edge ownership; the
    /// constructor validates all maps before any solver or output is used.
    pub fn from_encoded(
        global_graph: MicroBlossomSingle,
        encoded_windows: Vec<EncodedWindow>,
        edge_observables: Vec<Vec<usize>>,
        num_observables: usize,
    ) -> Result<Self, String> {
        if edge_observables.len() != global_graph.weighted_edges.len() {
            return Err("edge labels must align with global weighted edges".into());
        }
        for (eid, labels) in edge_observables.iter().enumerate() {
            let mut seen = BTreeSet::new();
            for &label in labels {
                if label >= num_observables || !seen.insert(label) {
                    return Err(format!("edge {eid} has an invalid or repeated observable label"));
                }
            }
        }
        if !encoded_windows.iter().any(|w| w.layer == WindowLayer::Top) {
            return Err("decoding requires an open top window".into());
        }
        let mut ids = BTreeSet::new();
        let mut owned_top_edges = BTreeSet::new();
        let global_virtuals: BTreeSet<_> = global_graph.virtual_vertices.iter().copied().collect();
        for window in &encoded_windows {
            if !ids.insert(&window.id) {
                return Err(format!("duplicate window ID: {}", window.id));
            }
            let init = &window.initializer;
            if init.vertex_num != window.positions.len()
                || init.vertex_num != window.detector_map.len()
                || init.weighted_edges.len() != window.edge_map.len()
            {
                return Err(format!("window {} has inconsistent graph/map lengths", window.id));
            }
            let virtuals: BTreeSet<_> = init.virtual_vertices.iter().copied().collect();
            if virtuals.iter().any(|&v| v >= init.vertex_num) {
                return Err(format!("window {} has an invalid virtual vertex", window.id));
            }
            let mut seen_detectors = BTreeSet::new();
            for (local, global) in window.detector_map.iter().enumerate() {
                match global {
                    Some(g)
                        if *g < global_graph.vertex_num
                            && !global_virtuals.contains(g)
                            && !virtuals.contains(&local)
                            && seen_detectors.insert(*g) => {}
                    None if virtuals.contains(&local) => {}
                    _ => return Err(format!("window {} has an invalid detector map", window.id)),
                }
            }
            if window.commit_detectors.iter().any(|d| !seen_detectors.contains(d)) {
                return Err(format!("window {} has an unmapped commit detector", window.id));
            }
            let mut local_edges = BTreeMap::new(); // global edge -> temporal crossing?
            for (local, &(l, r, weight)) in init.weighted_edges.iter().enumerate() {
                let eid = window.edge_map[local];
                if l >= init.vertex_num || r >= init.vertex_num || eid >= global_graph.weighted_edges.len() {
                    return Err(format!("window {} has an invalid edge map", window.id));
                }
                let global = &global_graph.weighted_edges[eid];
                if weight != global.w {
                    return Err(format!("window {} has an invalid edge map", window.id));
                }
                let crossing = match (window.detector_map[l], window.detector_map[r]) {
                    (Some(a), Some(b)) if (a == global.l && b == global.r) || (a == global.r && b == global.l) => false,
                    (Some(a), None) | (None, Some(a)) => {
                        let outside = if a == global.l {
                            global.r
                        } else if a == global.r {
                            global.l
                        } else {
                            return Err(format!("window {} edge {eid} has mismatched endpoints", window.id));
                        };
                        let temporal = !global_virtuals.contains(&outside);
                        if temporal && window.layer != WindowLayer::Top {
                            return Err(format!("closed window {} has a temporal edge {eid}", window.id));
                        }
                        temporal
                    }
                    _ => return Err(format!("window {} edge {eid} has mismatched endpoints", window.id)),
                };
                if local_edges.insert(eid, crossing).is_some() {
                    return Err(format!("window {} maps global edge {eid} twice", window.id));
                }
            }
            if window.layer == WindowLayer::Top {
                let commit: BTreeSet<_> = window.commit_detectors.iter().copied().collect();
                let expected: BTreeSet<_> = global_graph
                    .weighted_edges
                    .iter()
                    .enumerate()
                    .filter(|(_, e)| commit.contains(&e.l) || commit.contains(&e.r))
                    .map(|(eid, _)| eid)
                    .collect();
                if expected != window.commit_edges.iter().copied().collect() {
                    return Err(format!(
                        "window {} must own every edge incident to its commit detectors",
                        window.id
                    ));
                }
                let mut local_commits = BTreeSet::new();
                for &eid in &window.commit_edges {
                    if !local_edges.contains_key(&eid) || !local_commits.insert(eid) || !owned_top_edges.insert(eid) {
                        return Err(format!("window {} has overlapping or unmapped top commits", window.id));
                    }
                    if local_edges[&eid] {
                        return Err(format!("window {} cannot commit temporal edge {eid}", window.id));
                    }
                }
            } else if !window.commit_edges.is_empty() {
                return Err(format!("bottom window {} must commit its whole graph", window.id));
            }
        }
        // Keep the existing public single-label view for old callers. Encoded
        // decoding uses the full `Vec<Vec<usize>>` instead.
        let single_labels = edge_observables
            .iter()
            .map(|labels| (labels.len() == 1).then(|| labels[0]))
            .collect();
        Ok(Self {
            global_graph,
            windows: Vec::new(),
            edge_observables: single_labels,
            num_observables,
            encoded_windows: Some(encoded_windows),
            encoded_observables: edge_observables,
        })
    }

    /// Decode a syndrome and return the global prediction.
    ///
    /// `global_defects` are detector ids with odd syndrome in the *global*
    /// graph.  The method runs layer-0 windows in parallel (here simulated with
    /// a sequential loop; a real deployment would spawn one FPGA context per
    /// window), collects committed edges and artificial defects, then runs
    /// layer-1 windows.
    pub fn decode(&self, global_defects: Vec<usize>) -> ParallelDecodeResult {
        if self.encoded_windows.is_some() {
            return self
                .decode_encoded_shot(&global_defects)
                .expect("encoded shot failed; use decode_encoded_shot to handle the error");
        }
        let mut global_committed: BTreeSet<usize> = BTreeSet::new();
        let mut logical_parity = vec![false; self.num_observables];

        // --- Layer 0 : open, commit+buffer ---------------------------------
        // Artificial defects generated at seams, keyed by detector id
        let mut artificial_by_detector: BTreeMap<usize, usize> = BTreeMap::new(); // detector -> count (xor via toggle)
        let layer0_windows: Vec<&WindowSpec> = self.windows.iter().filter(|w| w.layer == WindowLayer::Top).collect();

        for window in layer0_windows {
            let (init, pos, maps) = build_window_initializer(&self.global_graph, window);
            let window_graph = MicroBlossomSingle::new(&init, &pos);

            // Map global defects that lie inside this window to local ids
            let local_defects: Vec<usize> = global_defects
                .iter()
                .filter_map(|&gv| {
                    // Check t containment via global position, not just map existence,
                    // because spatial virtuals are always mapped but never defects.
                    let t = self.global_graph.positions[gv].t;
                    if window.contains(t) {
                        maps.global_to_local[gv]
                    } else {
                        None
                    }
                })
                .collect();

            // Build inner solver (CPU+comb)
            let mut solver = SolverEmbeddedComb::new(
                window_graph,
                json!({
                    "dual": {
                        "sim_config": {
                            "support_offloading": false,
                            "support_layer_fusion": false
                        }
                    }
                }),
            );

            let syndrome = SyndromePattern::new_vertices(local_defects.clone());
            solver.solve_visualizer(&syndrome, None);
            let subgraph = solver.subgraph_visualizer(None);

            // Preserve parity at each commit detector by retaining all its edges.
            let mut committed_local: Vec<usize> = Vec::new();
            for &local_eid in &subgraph {
                let (l, r, _) = init.weighted_edges[local_eid];
                let endpoints = [l, r];
                let real = endpoints.iter().copied().filter(|v| !init.virtual_vertices.contains(v));
                if real.clone().any(|v| window.is_commit(pos[v].t)) {
                    let global_eid = maps.local_to_global_edge[local_eid];
                    let edge = &self.global_graph.weighted_edges[global_eid];
                    assert!(
                        [edge.l, edge.r]
                            .iter()
                            .copied()
                            .all(|v| self.global_graph.virtual_vertices.contains(&v)
                                || window.contains(self.global_graph.positions[v].t)),
                        "commit incident edge crosses outer window boundary; enlarge buffer"
                    );
                    committed_local.push(local_eid);
                }
            }

            // Map committed edges to global and update parity / artificial
            // To generate artificial defects we need to know which detectors are
            // flipped an odd number of times by committed edges *outside* the commit.
            // We compute the parity of committed edges' endpoints restricted to detectors
            // whose t is outside the commit interval → those are the seam/buffer detectors
            // that become artificial for the next layer.
            let mut flipped_outside: BTreeSet<usize> = BTreeSet::new();
            for &leid in &committed_local {
                let (l, r, _) = init.weighted_edges[leid];
                // Toggle both endpoints if they are non-virtual in local graph.
                // Virtual vertices (spatial or temporal) are not real detectors and do not create artificial defects.
                let is_virtual = |lv: usize| init.virtual_vertices.contains(&lv);
                for lv in [l, r] {
                    if is_virtual(lv) {
                        continue;
                    }
                    let gv = maps.local_to_global_vertex[lv];
                    if gv == usize::MAX {
                        continue; // temporal virtual sentinel
                    }
                    let t = self.global_graph.positions[gv].t;
                    // Endpoint outside commit => artificial
                    if t < window.commit_start || t >= window.commit_end {
                        toggle_set(&mut flipped_outside, gv);
                    }
                    // Endpoints inside commit are annihilated against the original syndrome
                    // inside the commit.  We do not need to track them separately because
                    // their parity is consumed: original defects inside commit are expected
                    // to be corrected by committed edges.  Artificial tracking only needs
                    // outside endpoints.  However, to avoid double-counting, we still need
                    // to know global parity: every committed edge contributes its observable,
                    // regardless of where its endpoints lie.
                }
                let geid = maps.local_to_global_edge[leid];
                global_committed.insert(geid);
                if let Some(obs) = self.edge_observables[geid] {
                    logical_parity[obs] ^= true;
                }
            }

            // Each flipped outside detector becomes an artificial defect for layer 1.
            // If the same detector is flipped by two committed edges from the same window,
            // the toggles cancel (even parity → no artificial).
            for det in flipped_outside {
                toggle_count(&mut artificial_by_detector, det);
            }
        }

        let virtuals: BTreeSet<_> = self.global_graph.virtual_vertices.iter().copied().collect();
        let mut residual: BTreeSet<_> = global_defects.iter().copied().collect();
        for &eid in &global_committed {
            toggle_global_edge(&mut residual, &self.global_graph, &virtuals, eid);
        }
        for &d in &residual {
            let t = self.global_graph.positions[d].t;
            assert!(
                !self.windows.iter().any(|w| w.layer == WindowLayer::Top && w.is_commit(t)),
                "layer 0 left residual detector {d} inside a top commit"
            );
            assert!(
                self.windows.iter().any(|w| w.layer == WindowLayer::Bottom && w.contains(t)),
                "layer 0 residual detector {d} is outside layer-1 coverage"
            );
        }

        // --- Layer 1 : closed, fully committed -------------------------------
        // Layer-1 input = (global defects inside layer-1 window) XOR (artificial defects from neighbours)
        let layer1_windows: Vec<&WindowSpec> = self.windows.iter().filter(|w| w.layer == WindowLayer::Bottom).collect();

        for window in layer1_windows {
            let (init, pos, maps) = build_window_initializer(&self.global_graph, window);

            // Start with global defects that fall inside this window's interval
            let mut input_defects: BTreeSet<usize> = BTreeSet::new();
            for &gv in &global_defects {
                let t = self.global_graph.positions[gv].t;
                if window.contains(t) {
                    input_defects.insert(gv);
                }
            }
            // XOR artificial defects that lie inside this window
            for (&art_det, &count) in &artificial_by_detector {
                if count % 2 == 1 {
                    let t = self.global_graph.positions[art_det].t;
                    if window.contains(t) {
                        if !input_defects.insert(art_det) {
                            input_defects.remove(&art_det);
                        }
                    }
                }
            }

            if input_defects.is_empty() {
                // No syndrome to decode in this window — still need to check that
                // there is no leftover artificial parity that should have been handled,
                // but for prototype we skip empty windows.
                continue;
            }

            let local_defects: Vec<usize> = input_defects.iter().filter_map(|&gv| maps.global_to_local[gv]).collect();

            let window_graph = MicroBlossomSingle::new(&init, &pos);
            let mut solver = SolverEmbeddedComb::new(
                window_graph,
                json!({
                    "dual": {
                        "sim_config": {
                            "support_offloading": false,
                            "support_layer_fusion": false
                        }
                    }
                }),
            );
            let syndrome = SyndromePattern::new_vertices(local_defects);
            solver.solve_visualizer(&syndrome, None);
            let subgraph = solver.subgraph_visualizer(None);

            // Layer-1 windows are fully committed (no buffer)
            for &leid in &subgraph {
                let geid = maps.local_to_global_edge[leid];
                if global_committed.insert(geid) {
                    if let Some(obs) = self.edge_observables[geid] {
                        logical_parity[obs] ^= true;
                    }
                }
            }
        }

        let mut committed_edges: Vec<usize> = global_committed.into_iter().collect();
        committed_edges.sort_unstable();

        // Silence unused variable warning for pos in layer1 (used for future extension)
        let _ = pos_len_check(&self.global_graph);

        ParallelDecodeResult {
            committed_edges,
            logical_parity,
            total_offloaded: 0,
        }
    }

    /// Decode a real shot using the toolchain's detector-membership windows.
    /// Top windows see the input syndrome; only their owned edges are committed.
    /// Bottom windows see the *full* residual S XOR boundary(top commits), not
    /// merely the outside endpoints, and commit every selected local edge.
    /// An uncorrectable shot is an error, never a successful prediction.
    pub fn decode_encoded_shot(&self, defects: &[usize]) -> Result<ParallelDecodeResult, String> {
        let windows = self
            .encoded_windows
            .as_ref()
            .ok_or("decoder was not constructed from encoded windows")?;
        let global_virtuals: BTreeSet<_> = self.global_graph.virtual_vertices.iter().copied().collect();
        let mut residual = BTreeSet::new();
        for &detector in defects {
            if detector >= self.global_graph.vertex_num || global_virtuals.contains(&detector) || !residual.insert(detector)
            {
                return Err(format!("invalid or duplicate global defect {detector}"));
            }
        }
        let initial = residual.clone();
        let mut committed = BTreeSet::new();
        for window in windows.iter().filter(|w| w.layer == WindowLayer::Top) {
            let tentative = solve_encoded_window(window, &initial)?;
            let owned: BTreeSet<_> = window.commit_edges.iter().copied().collect();
            for eid in tentative {
                if owned.contains(&eid) {
                    toggle_set(&mut committed, eid);
                    toggle_global_edge(&mut residual, &self.global_graph, &global_virtuals, eid);
                }
            }
        }
        for window in windows.iter().filter(|w| w.layer == WindowLayer::Top) {
            if let Some(d) = window.commit_detectors.iter().find(|d| residual.contains(d)) {
                return Err(format!("layer 0 left residual detector {d} inside top commit {}", window.id));
            }
        }
        let bottom_coverage: BTreeSet<_> = windows
            .iter()
            .filter(|w| w.layer == WindowLayer::Bottom)
            .flat_map(|w| w.detector_map.iter().flatten().copied())
            .collect();
        if let Some(d) = residual.iter().find(|d| !bottom_coverage.contains(d)) {
            return Err(format!("layer 0 residual detector {d} is not covered by any layer-1 window"));
        }
        // All bottom windows consume the same top-layer residual. The final
        // boundary check below catches gaps, overlap and unmatched defects.
        let bottom_input = residual.clone();
        for window in windows.iter().filter(|w| w.layer == WindowLayer::Bottom) {
            for eid in solve_encoded_window(window, &bottom_input)? {
                toggle_set(&mut committed, eid);
                toggle_global_edge(&mut residual, &self.global_graph, &global_virtuals, eid);
            }
        }
        if !residual.is_empty() {
            return Err(format!("unmatched residual detectors: {residual:?}"));
        }
        let mut logical_parity = vec![false; self.num_observables];
        for &eid in &committed {
            for &observable in &self.encoded_observables[eid] {
                logical_parity[observable] ^= true;
            }
        }
        Ok(ParallelDecodeResult {
            committed_edges: committed.into_iter().collect(),
            logical_parity,
            total_offloaded: 0,
        })
    }

    /// Convenience: build windows automatically from the global detector time
    /// range using the given commit/buffer sizes and scheme, then decode.
    pub fn decode_auto(
        &self,
        global_defects: Vec<usize>,
        commit_size: f64,
        buffer_size: f64,
        gap: f64,
    ) -> ParallelDecodeResult {
        // This is a helper that regenerates windows on the fly; normally windows
        // are precomputed from the global time range at construction.
        let _ = (commit_size, buffer_size, gap);
        self.decode(global_defects)
    }
}

fn toggle_global_edge(residual: &mut BTreeSet<usize>, global: &MicroBlossomSingle, virtuals: &BTreeSet<usize>, eid: usize) {
    let edge = &global.weighted_edges[eid];
    for detector in [edge.l, edge.r] {
        if !virtuals.contains(&detector) {
            toggle_set(residual, detector);
        }
    }
}

fn solve_encoded_window(window: &EncodedWindow, global_defects: &BTreeSet<usize>) -> Result<Vec<usize>, String> {
    let local_defects: Vec<_> = window
        .detector_map
        .iter()
        .enumerate()
        .filter_map(|(local, global)| global.filter(|id| global_defects.contains(id)).map(|_| local))
        .collect();
    if local_defects.is_empty() {
        return Ok(Vec::new());
    }
    let init = &window.initializer;
    let virtuals: BTreeSet<_> = init.virtual_vertices.iter().copied().collect();
    let mut adjacency = vec![Vec::new(); init.vertex_num];
    for &(l, r, _) in &init.weighted_edges {
        adjacency[l].push(r);
        adjacency[r].push(l);
    }
    // A disconnected component with odd parity and no virtual boundary cannot
    // be matched. Reject before calling the inner solver instead of panicking.
    let mut defect_flags = vec![false; init.vertex_num];
    for &local in &local_defects {
        defect_flags[local] = true;
    }
    let mut seen = vec![false; init.vertex_num];
    for start in 0..init.vertex_num {
        if seen[start] {
            continue;
        }
        let mut stack = vec![start];
        seen[start] = true;
        let mut odd = false;
        let mut boundary = false;
        while let Some(v) = stack.pop() {
            odd ^= defect_flags[v];
            boundary |= virtuals.contains(&v);
            for &next in &adjacency[v] {
                if !seen[next] {
                    seen[next] = true;
                    stack.push(next);
                }
            }
        }
        if odd && !boundary {
            return Err(format!("window {} has an unmatchable syndrome component", window.id));
        }
    }
    let window_graph = MicroBlossomSingle::new(init, &window.positions);
    let mut solver = SolverEmbeddedComb::new(
        window_graph,
        json!({
            "dual": { "sim_config": {
                "support_offloading": false,
                "support_layer_fusion": false
            }}
        }),
    );
    solver.solve_visualizer(&SyndromePattern::new_vertices(local_defects), None);
    solver
        .subgraph_visualizer(None)
        .into_iter()
        .map(|local| {
            window
                .edge_map
                .get(local)
                .copied()
                .ok_or_else(|| format!("window {} returned an out-of-range correction edge {local}", window.id))
        })
        .collect()
}

fn toggle_set(set: &mut BTreeSet<usize>, v: usize) {
    if !set.insert(v) {
        set.remove(&v);
    }
}

fn toggle_count(map: &mut BTreeMap<usize, usize>, v: usize) {
    let c = map.entry(v).or_insert(0);
    *c += 1;
    if *c % 2 == 0 {
        map.remove(&v);
    }
}

fn pos_len_check(g: &MicroBlossomSingle) -> usize {
    g.positions.len()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::resources::MicroBlossomSingle;
    use fusion_blossom::util::*;
    use micro_blossom_nostd::window::{WindowBoundary, WindowGenerationConfig, WindowScheme};

    fn tiny_line_graph() -> (MicroBlossomSingle, Vec<Option<usize>>) {
        // 4 detectors in a line, t = 0,1,2,3, edges between neighbours, spatial boundaries at ends via virtual.
        // This is a 1-D repetition code time-rolled: detectors are spacetime points.
        let initializer = SolverInitializer::new(
            5, // 4 real + 1 virtual
            vec![(0, 1, 10), (1, 2, 10), (2, 3, 10), (0, 4, 10), (3, 4, 10)],
            vec![4],
        );
        let positions = vec![
            VisualizePosition::new(0.0, 0.0, 0.0),
            VisualizePosition::new(0.0, 0.0, 1.0),
            VisualizePosition::new(0.0, 0.0, 2.0),
            VisualizePosition::new(0.0, 0.0, 3.0),
            VisualizePosition::new(0.0, 0.0, 0.0), // virtual
        ];
        let graph = MicroBlossomSingle::new(&initializer, &positions);
        // Edge 1 (1-2) flips observable
        let edge_obs = vec![None, Some(0), None, None, None];
        (graph, edge_obs)
    }

    #[test]
    fn window_initializer_open_vs_closed() {
        let (global, _) = tiny_line_graph();
        let open_win = WindowSpec {
            id: "A0".into(),
            layer: WindowLayer::Top,
            t_start: 0.0,
            t_end: 2.0,
            commit_start: 0.5,
            commit_end: 1.5,
            boundary: WindowBoundary::Open,
        };
        let (init_open, _, _) = build_window_initializer(&global, &open_win);
        assert!(init_open.virtual_vertices.len() >= 2); // spatial + 2 temporal

        let closed_win = WindowSpec {
            id: "B0".into(),
            layer: WindowLayer::Bottom,
            t_start: 0.5,
            t_end: 1.5,
            commit_start: 0.5,
            commit_end: 1.5,
            boundary: WindowBoundary::Closed,
        };
        let (init_closed, _, _) = build_window_initializer(&global, &closed_win);
        assert!(init_closed.virtual_vertices.len() == 1); // only spatial
    }

    #[test]
    fn parallel_decode_no_error() {
        let (global, edge_obs) = tiny_line_graph();
        // Windows covering [0,4) with commit 1 each, buffer 1
        let cfg = WindowGenerationConfig {
            commit_size: 1.0,
            buffer_size: 1.0,
            scheme: WindowScheme::Contiguous,
        };
        let windows = cfg.generate(0.0, 4.0);
        let decoder = ParallelWindowDecoder::new(global, windows, edge_obs, 1);
        // No defects -> no correction, parity false
        let result = decoder.decode(vec![]);
        assert_eq!(result.committed_edges, Vec::<usize>::new());
        assert_eq!(result.logical_parity, vec![false]);
    }

    #[test]
    fn parallel_decode_single_defect_pair() {
        let (global, edge_obs) = tiny_line_graph();
        let cfg = WindowGenerationConfig {
            commit_size: 1.0,
            buffer_size: 1.0,
            scheme: WindowScheme::Contiguous,
        };
        let windows = cfg.generate(0.0, 4.0);
        let decoder = ParallelWindowDecoder::new(global.clone(), windows, edge_obs, 1);
        // Defects at 1 and 2 should be matched via edge 1 (middle) which flips observable
        let result = decoder.decode(vec![1, 2]);
        assert!(result.committed_edges.contains(&1));
        assert_eq!(result.logical_parity, vec![true]);
    }

    #[test]
    fn contiguous_generated_windows_preserve_all_syndromes_with_full_context() {
        let (global, edge_obs) = tiny_line_graph();
        let cfg = WindowGenerationConfig {
            commit_size: 1.0,
            buffer_size: 4.0,
            scheme: WindowScheme::Contiguous,
        };
        let windows = cfg.generate(0.0, 4.0);
        let decoder = ParallelWindowDecoder::new(global.clone(), windows, edge_obs, 1);
        let virtuals = global.virtual_vertices.iter().copied().collect();
        for mask in 0..16 {
            let defects: Vec<_> = (0..4).filter(|d| mask & (1 << d) != 0).collect();
            let result = decoder.decode(defects.clone());
            let mut residual = defects.into_iter().collect();
            for &eid in &result.committed_edges {
                toggle_global_edge(&mut residual, &global, &virtuals, eid);
            }
            assert!(residual.is_empty(), "syndrome mask {mask}: {residual:?}");
            assert_eq!(result.logical_parity, vec![result.committed_edges.contains(&1)]);
        }
    }

    #[test]
    #[should_panic(expected = "claimed by multiple top windows")]
    fn adjacent_top_commits_still_reject_shared_edges() {
        let (global, edge_obs) = tiny_line_graph();
        let windows = (0..4).map(|i| WindowSpec {
            id: format!("old-C{i}"), layer: WindowLayer::Top,
            t_start: 0.0, t_end: 4.0,
            commit_start: i as f64, commit_end: (i + 1) as f64,
            boundary: WindowBoundary::Open,
        }).collect();
        ParallelWindowDecoder::new(global, windows, edge_obs, 1);
    }

    #[test]
    fn generate_riverlane_windows() {
        let cfg = WindowGenerationConfig {
            commit_size: 2.0,
            buffer_size: 2.0,
            scheme: WindowScheme::Riverlane { gap: 2.0 },
        };
        let windows = cfg.generate(0.0, 14.0);
        assert!(windows.iter().any(|w| w.id.starts_with('A')));
        assert!(windows.iter().any(|w| w.id.starts_with('B')));
        for w in windows.iter().filter(|w| w.layer == WindowLayer::Bottom) {
            assert_eq!(w.boundary, WindowBoundary::Closed);
        }
    }
}
