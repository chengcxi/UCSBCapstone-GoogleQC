//! Parallel-window decoder orchestration for Micro Blossom CPUs
//!
//! This is the **CPU-side controller** that enables Micro Blossom to process
//! both window types required by the project vision:
//!
//! * **Layer-0 (top)** decoders are *commit/buffer-aware*: they receive a
//!   window graph with open temporal boundaries, decode it with any inner
//!   MWPM solver (e.g. `SolverEmbeddedComb`, `SolverDualComb`, or a pure
//!   software `SolverSerial`), then split the tentative correction into
//!   committed (inside `commit_start..commit_end`) and discarded (buffer) parts.
//!   The committed part updates a global correction prediction and produces
//!   *residual syndromes* (artificial detection events on the seam) via the
//!   oracle in `window_oracle`.
//!
//! * **Layer-1 (bottom)** decoders *receive residual syndromes*: their window
//!   graphs have closed temporal boundaries and are fully committed.  Their
//!   input is the union of (i) global defects that lie inside the window's
//!   `t` interval and (ii) artificial defects generated by neighbouring
//!   layer-0 windows.  Both layers commit to the **same global prediction**
//!   (XOR of observable flips), as required.
//!
//! The scheme is a direct implementation of Skoric *et al.* [2209.08552]
//! Fig. 3 and Tan *et al.* [2209.09219] Fig. 2, with the Micro Blossom
//! heterogeneous split (Wu *et al.* [2502.14787]): each window can be decoded
//! by a separate FPGA context (or CPU thread) in parallel; only the small
//! artificial syndromes and observable parities need to be communicated.
//!
//! # Two-layer schedule
//!
//! ```text
//!   t_min                           t_max
//!   |----A0----|         |----A1----|- ...
//!        |----B0----|
//!   [buf|commit|buf]  <- A windows, open (buffer = d)
//!        [  fully committed ] <- B windows, closed
//! ```
//!
//! *A* windows are decoded in parallel (no dependencies).  A window's
//! `commit` produces artificial defects at its two seams (`commit_start` and
//! `commit_end`).  A *B* window can start as soon as its two neighbouring *A*
//! windows have finished, because it needs their artificial defects.
//! Throughput scales as `N_par * (n_com + n_W) * tau_rd >= 2*tau_W`
//! (Eq. 2 in 2209.08552).
//!
//! # Physical vs temporal boundaries
//!
//! Spatial (code) boundaries are preserved in both layers as virtual vertices
//! (McEwen *et al.* [2302.02192]).  Only the *temporal* cuts are open/closed:
//! open windows add a temporal virtual node per time cut with edges that copy
//! the weight of the original crossing edge; closed windows omit those edges.
//! This is implemented in `build_window_initializer`.

